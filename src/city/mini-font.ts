// A 3x5 pixel face for mid-distance signage: once a letter is ~5 cells tall, each font pixel
// gets a whole character cell, so words stay readable from much further than the 8x8 face
// (which needs ~9 cells). Rows top to bottom, "1" = lit. Lowercase maps to capitals.
const GLYPHS: Record<string, string> = {
  A: "010101111101101", B: "110101110101110", C: "011100100100011", D: "110101101101110", E: "111100110100111",
  F: "111100110100100", G: "011100101101011", H: "101101111101101", I: "111010010010111", J: "001001001101010",
  K: "101101110101101", L: "100100100100111", M: "101111111101101", N: "110101101101101", O: "010101101101010",
  P: "110101110100100", Q: "010101101110011", R: "110101110101101", S: "011100010001110", T: "111010010010010",
  U: "101101101101111", V: "101101101101010", W: "101101111111101", X: "101101010101101", Y: "101101010010010",
  Z: "111001010100111", "0": "111101101101111", "1": "010110010010111", "2": "110001010100111", "3": "110001010001110",
  "4": "101101111001001", "5": "111100110001110", "6": "011100111101111", "7": "111001010010010", "8": "111101111101111",
  "9": "111101111001110", ".": "000000000000010", ",": "000000000010100", ":": "000010000010000", "-": "000000111000000",
  "+": "000010111010000", "/": "001001010100100", "%": "101001010100101", "!": "010010010000010", "'": "010010000000000",
  "$": "011110010011110", "&": "010101010101011", "?": "110001010000010", "(": "010100100100010", ")": "010001001001010",
  "=": "000111000111000", "#": "101111101111101", "*": "101010101000000", "<": "001010100010001", ">": "100010001010100",
};

/** Two bytes per printable ASCII glyph (15 bits, MSB = top-left), ready for the text texture. */
export function miniFontBytes(): Uint8Array {
  const bytes = new Uint8Array(95 * 2);
  for (let code = 32; code < 127; code++) {
    const bits = GLYPHS[String.fromCharCode(code).toUpperCase()] ?? "000000000000000";
    const value = parseInt(bits, 2);
    bytes[(code - 32) * 2] = value & 255;
    bytes[(code - 32) * 2 + 1] = value >> 8;
  }
  return bytes;
}
